// Netlify build script: dynamically generates _redirects when BACKEND_URL is set
const fs = require('fs');
const path = require('path');

const backendUrl = (process.env.BACKEND_URL || 'https://xyz-auto-service.onrender.com').trim().replace(/\/+$/, '');
const frontendDir = path.resolve(__dirname, 'frontend');
const redirectsTarget = fs.existsSync(frontendDir) ? path.join(frontendDir, '_redirects') : path.join(__dirname, '_redirects');

if (backendUrl) {
  const content = `# Auto-generated by build-redirects.js
/api/*  ${backendUrl}/api/:splat  200!
/*      /index.html                     200
`;
  try {
    fs.writeFileSync(redirectsTarget, content, 'utf8');
    console.log(`[build-redirects] Configured API rewrite proxy to: ${backendUrl}/api/:splat`);
  } catch (err) {
    console.error('[build-redirects] Failed to write _redirects:', err);
  }
}
